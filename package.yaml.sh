#!/bin/bash

# Source of package.json -- edit this file, then run ./package.yaml.sh to regenerate package.json
# Note: the heredoc is quoted ('EOF'), so bash leaves $, backticks and backslashes in the YAML alone.
#
# Don't pipe to package.json directly - that would truncate it before npx/node start, and on a
# YAML error in this file, that would leave package.json empty.
set -euo pipefail
npx js-yaml <<'EOF' | sponge package.json
---
name: latex.js
description: JavaScript LaTeX to HTML5 translator
version: 0.13.1

author:
    name: Michael Brade
    email: brade@kde.org

keywords:
    - pegjs
    - peggy
    - latex
    - parser
    - html5

bin:
    latex.js: bin/latex.js

type: module

exports:
    # custom condition only used by tsconfig "customConditions": type-check against the source, no build needed;
    # Node, tsx and bundlers don't know it, so at runtime "latex.js" resolves to dist/
    latex.js-source: ./src/index.ts
    import:
        types: ./dist/types/index.d.ts      # ESM types
        default: ./dist/latex.js
    require:
        types: ./dist/types/index.d.cts     # CommonJS types
        default: ./dist/latex.cjs

browser: ./dist/latex.umd.cjs


files:
    - bin/latex.js
    - bin/latex.js.map
    - dist/types/       # .d.ts and .d.cts files generated by unplugin-dts
    - dist/latex.cjs
    - dist/latex.cjs.map
    - dist/latex.js
    - dist/latex.js.map
    - dist/latex.umd.cjs
    - dist/latex.umd.cjs.map
    - dist/css/
    - dist/fonts/
    - dist/js/
    - dist/packages/
    - dist/documentclasses/

scripts:
    # IMPORTANT: keep the ; at the end of each script to signal bash to stop interpreting,
    # otherwise calling e.g. "npm run clean /" would result in "rm -rf /"

    # typescript (7) and @typescript/old (6, a dependency of @typescript/typescript6) both have a "tsc" bin,
    # and npm may link either one; make sure node_modules/.bin/tsc is TypeScript 7 (also used by
    # vite-plugin-checker during vite build).
    # use prepare, not postinstall: it must run only on npm install/ci in this repo and not when
    # latex.js is installed as a dependency (postinstall would run then) because no patch-package
    # or typescript exist then
    prepare: >-
        patch-package &&
        ln -sf ../typescript/bin/tsc node_modules/.bin/tsc
        ;

    # rm -rf all elements up to the first ;
    # then unregister the gh-pages worktree website/ (if there is one) and prune stale worktree entries
    clean: >-
        rimraf
        dist bin
        test/coverage
        docs/.vitepress/.temp
        docs/.vitepress/cache
        ;
        git worktree remove --force website 2>/dev/null;
        git worktree prune;
        rimraf website .website.git
        ;

    # runs AFTER vite build (which already empties dist/), so don't delete anything here:
    # dist/types/ holds the .d.ts files generated by unplugin-dts;
    # css/katex.css and fonts/katex.css are generated from the installed katex (lib/katex-css.mjs)
    assets: >-
        mkdirp dist/css dist/js dist/fonts dist/documentclasses dist/packages &&
        touch dist/documentclasses/.keep dist/packages/.keep &&
        rsync -a src/css/ dist/css/ &&
        rsync -a public/fonts/ dist/fonts/ &&
        rsync -a node_modules/katex/dist/fonts/*.woff2 dist/fonts/ &&
        node lib/katex-css.mjs dist &&
        rsync -a public/js/ dist/js/
        ;

    # docs: vue-tsc also checks .vue files; it needs TypeScript 6, see lib/vue-tsc.cjs
    typecheck: >-
        tsc --noEmit &&
        tsc --noEmit -p test &&
        node lib/vue-tsc.cjs --noEmit -p docs
        ;

    # library into dist/, then the CLI into bin/latex.js (vite.cli.config.ts), then the static assets
    devbuild: >-
        vite build --mode development &&
        vite build -c vite.cli.config.ts --mode development &&
        npm run assets
        ;

    build: >-
        vite build --mode production &&
        vite build -c vite.cli.config.ts --mode production &&
        npm run assets
        ;


    # docs/website and playground

    devdocs: vitepress dev docs;

    # builds the website into the gh-pages worktree website/ and commits it there (doesn't push);
    # vitepress empties its outDir, so the worktree's .git file is moved away during the build
    # and always moved back, even if the build fails
    docs: >-
        npm run build &&
        { [ -d website ] || { git worktree prune && git worktree add website gh-pages; }; } &&
        mv website/.git .website.git &&
        ( vitepress build docs; status=$?; mv .website.git website/.git; exit $status ) &&
        cd website &&
        git add . &&
        { git diff --cached --quiet || git commit -m 'regenerated website'; }
        ;


    # unit tests
    test: vitest run --project unit;

    # coverage needs a build with source maps (npm run build); report in test/coverage/
    testc: vitest run --coverage --project unit;

    # integration tests
    test-int: vitest run --project integration;

dependencies:
    ### CLI dependencies

    commander: 8.x
    he: 2.x
    fs-extra: 11.4.x
    js-beautify: 2.0.x

    svgdom: ^0.1.29
    hyphen: 1.14.x

    #xmldom: 0.3.x
    #jsdom: 16.x
    #cheerio: 1.0.x


devDependencies:
    patch-package: 8.0.x
    js-yaml: 5.x            # generates package.json from package.yaml.sh

    ### actual runtime dependencies, but bundled by vite

    katex: 0.19.x
    "@svgdotjs/svg.js": 3.2.x

    ### building

    peggy: 5.1.x
    mkdirp: 3.x
    rimraf: 6.x

    typescript: 7.0.x
    "@typescript/typescript6": 6.0.x # JS compiler API for unplugin-dts and vue-tsc (TS 7 has none)
    tsx: ^4.22.4
    "@tsconfig/node-ts": ^23.6.4
    "@tsconfig/node22": ^22.0.7
    # "@microsoft/api-extractor": 7.60.x

    ### docs

    vitepress: 2.0.0-alpha.21

    split-grid: 1.0.x
    "@codemirror/autocomplete": 6.x
    "@codemirror/commands": 6.x
    "@codemirror/language": 6.x
    "@codemirror/lint": 6.x
    "@codemirror/search": 6.x
    "@codemirror/state": 6.x
    "@codemirror/view": 6.x
    "@codemirror/theme-one-dark": 6.x
    codemirror-lang-latex: 0.6.x
    vue-tsc: 3.3.x
    vue-codemirror6: 1.5.x
    sass-embedded: 1.108.x

    ### bundling

    vite: 8.3.x
    vite-plugin-node-polyfills: 0.28.x
    vite-plugin-checker: 1.0.x
    unplugin-dts: 1.1.x
    rollup-plugin-visualizer: 7.1.x

    "@rolldown/plugin-babel": 0.3.x
    "@babel/plugin-proposal-decorators": 8.0.x

    ### testing

    vitest: 5.1.x
    "@vitest/coverage-v8": 5.1.x

    slugify: 1.6.x

    puppeteer: 25.17.x

    "@blazediff/core-native": 7.0.x       # screenshot diffs

    serve-handler: 6.x
    "@types/serve-handler": ^6.1.4

    ### types

    "@types/he": ^1.2.3
    "@types/hyphen": 1.14.x
    "@types/svgdom": ^0.1.2
    "@types/fs-extra": ^11.0.4
    "@types/js-beautify": ^1.14.3

overrides:
    minimatch: ^11.0.5
    serve-handler:
        minimatch: 3.1.5


# first time: install browsers with "npx puppeteer browsers install" after "npm i"
puppeteer:
    chrome:
        skipDownload: false
    firefox:
        skipDownload: false

repository:
    type: git
    url: git+https://github.com/michael-brade/LaTeX.js.git

