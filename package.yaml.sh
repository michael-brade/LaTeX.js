    #cheerio: 1.0.x


devDependencies:
    patch-package: 8.0.x
    js-yaml: 5.x            # generates package.json from package.yaml.sh

    ### actual runtime dependencies, but bundled by vite

    katex: ^0.16.10
    "@svgdotjs/svg.js": 3.2.x

    ### building

    peggy: 5.1.x
    mkdirp: 3.x
    rimraf: 6.x

    typescript: 7.0.x
    "@typescript/typescript6": 6.0.x # JS compiler API for unplugin-dts and vue-tsc (TS 7 has none)
    tsx: ^4.22.4
    "@tsconfig/node-ts": ^23.6.4
    "@tsconfig/node22": ^22.0.7
    # "@microsoft/api-extractor": 7.60.x

    ### docs

    vitepress: ^1.6.4

    split-grid: 1.0.x
    "@codemirror/autocomplete": 6.x
