    "@types/tmp": ^0.2.6

    puppeteer: 25.17.x
    pixelmatch: 8.x

    pngjs: 7.0.x        # really needed??
    "@types/pngjs": ^6.0.5

    c8: 12.x
    codecov: 3.x

    serve-handler: 6.x
    "@types/serve-handler": ^6.1.4

    ### types

    "@types/he": ^1.2.3
    "@types/hyphen": 1.14.x
    "@types/svgdom": ^0.1.2
    "@types/fs-extra": ^11.0.4
    "@types/js-beautify": ^1.14.3

mocha:
    node-option:
        - import=tsx
    file:
        - test/lib/globals.ts
        - test/lib/setup.ts
    reporter: cypress-multi-reporters
    reporterOptions:
        reporterEnabled: spec, mocha-junit-reporter
        mochaJunitReporterReporterOptions:
            mochaFile: ./test/test-results.xml
    inlineDiffs: true
    timeout: 10000
    ui: bdd
    checkLeaks: true
    sort: true
    reporterOption: maxDiffSize=0

