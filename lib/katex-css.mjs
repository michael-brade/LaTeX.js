#!/usr/bin/env node

// Generates the KaTeX stylesheets from the installed katex package (called by "npm run assets"):
//
//  - <outDir>/fonts/katex.css: only the @font-face rules, woff2 only (npm run assets copies only woff2
//    to <outDir>/fonts). A page that shows LaTeX.js output in a shadow DOM (like <latex-js>) has to
//    load this one itself, @font-face is ignored in a shadow DOM.
//  - <outDir>/css/katex.css: the rest of KaTeX's stylesheet, importing ../fonts/katex.css.
//
// usage: node lib/katex-css.mjs <outDir>

import fs from 'node:fs';
import path from 'node:path';

import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);


const outDir = process.argv[2];
if (!outDir) {
    console.error('usage: katex-css.mjs <out dir>');
    process.exit(2);
}

const { version } = require('katex/package.json');
const css = fs.readFileSync(require.resolve('katex/dist/katex.css'), 'utf8');

// find all @font-face rules
const fontFaceRe = /@font-face\s*\{[^}]*\}\s*/g;
const fontFaces = css.match(fontFaceRe);
if (!fontFaces?.length)
    throw new Error('katex-css: no @font-face rules found in katex.css');

// remove everything but woff2 urls/formats
const woff2Only = fontFaces.map(rule => {
    const woff2 = rule.match(/url\(["']?fonts\/([^"')]+\.woff2)["']?\)\s*format\(["']woff2["']\)/);
    if (!woff2)
        throw new Error('katex-css: no woff2 font in ' + rule);

    return rule.replace(/src:[^;]*;/, `src: url("${woff2[1]}") format("woff2");`);
});

// check that no other url() statements remain
const rest = css.replace(fontFaceRe, '');
if (/url\(/.test(rest))
    throw new Error('katex-css: unexpected url() outside of @font-face, it would need rewriting');

// now write both css files
const header = `/* generated by lib/katex-css.mjs from katex@${version} */\n`;

fs.mkdirSync(path.join(outDir, 'fonts'), { recursive: true });
fs.mkdirSync(path.join(outDir, 'css'), { recursive: true });

fs.writeFileSync(path.join(outDir, 'fonts/katex.css'), header + woff2Only.join(''));
fs.writeFileSync(path.join(outDir, 'css/katex.css'), header + '@import url("../fonts/katex.css");\n\n' + rest);
